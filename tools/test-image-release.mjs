function extract(path, name) {
  const s=fs.readFileSync(path,'utf8');
  const start=s.indexOf('function '+name+'(');
  assert.ok(start>=0,name);
  const end=s.indexOf('\n}',start);
  assert.ok(end>start,name);
  return s.slice(start,end+2);
}
