import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const source = await readFile(new URL('./b4-lava-river-geometry.js', import.meta.url), 'utf8');
const {createLavaRiverData,createLavaSolidData}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const d=createLavaRiverData();
assert.equal(d.positions.length,97*19*3);
assert.equal(d.indices.length,96*18*6);
assert.ok(d.positions.every(Number.isFinite));
assert.ok(d.uvs.every(v=>v>=0&&v<=1));
const xs=[];for(let i=0;i<=96;i++)xs.push(d.positions[3*(i*19+9)]);
assert.ok(Math.max(...xs)-Math.min(...xs)>0.6);
const y=d.positions.filter((_,i)=>i%3===1);
assert.ok(Math.max(...y)-Math.min(...y)>0.12);
const solid=createLavaSolidData();
assert.equal(solid.positions.length,2*d.positions.length);
assert.ok(solid.indices.every(i=>i>=0&&i<solid.positions.length/3));
assert.ok(solid.positions.every(Number.isFinite));
assert.ok(Math.min(...solid.positions.filter((_,i)=>i%3===1))<Math.min(...y));
console.log('PASS: curved river, crown, flow UVs, finite vertices, underside and walls');
